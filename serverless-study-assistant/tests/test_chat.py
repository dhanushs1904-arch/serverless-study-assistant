"""Chat and AI Provider Tests
Tests rule-based fallback, Groq API mocks, and provider error resilience.
"""

from unittest.mock import MagicMock, patch
import pytest
from fastapi.testclient import TestClient
from app.config import settings
from app.model_provider import model_provider


def test_chat_fallback_scrum_topic(client: TestClient):
    """Test fallback accurately identifies Scrum questions."""
    response = client.post("/api/chat", json={"message": "What is the role of a Scrum Master?"})
    assert response.status_code == 200
    data = response.json()
    assert data["response_mode"] == "fallback"
    assert "Scrum" in data["reply"]
    assert "Sprint" in data["reply"]
    assert data["duration_ms"] > 0


