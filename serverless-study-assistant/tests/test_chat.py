def test_mocked_groq_ai_success():
    """Test that configured Groq provider successfully formats AI responses."""
    mock_choice = MagicMock()
    mock_choice.message.content = "Academic explanation generated by LLaMA 3.3 70B via Groq API."

    mock_completion = MagicMock()
    mock_completion.choices = [mock_choice]

    mock_groq_client = MagicMock()
    mock_groq_client.chat.completions.create.return_value = mock_completion

    orig_key = settings.GROQ_API_KEY
    try:
        settings.GROQ_API_KEY = "gsk_mock_valid_api_key_for_testing"
        with patch.object(model_provider, "_get_client", return_value=mock_groq_client):
            reply, mode, model_id = model_provider.generate_response("Explain quantum computing")
            assert mode == "ai"
            assert "LLaMA 3.3 70B" in reply
            assert model_id == settings.GROQ_MODEL
    finally:
        settings.GROQ_API_KEY = orig_key


def test_mocked_groq_ai_exception_routes_to_fallback():
    """Test that Groq provider errors gracefully fall back to deterministic response."""
    mock_groq_client = MagicMock()
    mock_groq_client.chat.completions.create.side_effect = Exception("Groq API 429 Rate Limit Exceeded")

    orig_key = settings.GROQ_API_KEY
    try:
        settings.GROQ_API_KEY = "gsk_mock_valid_api_key_for_testing"
        with patch.object(model_provider, "_get_client", return_value=mock_groq_client):
            reply, mode, model_id = model_provider.generate_response("Explain TCP handshake")
            assert mode == "fallback"
            assert model_id == "heuristic-academic-v1"
            assert "Switched to Rule-Based Fallback" in reply
            assert "TCP" in reply
    finally:
        settings.GROQ_API_KEY = orig_key
